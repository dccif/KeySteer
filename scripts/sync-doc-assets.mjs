import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = resolve(root, 'docs/public/generated')
const generatedSource = resolve(root, 'docs/.vitepress/generated')

async function packageVersion() {
  const manifest = await readFile(resolve(root, 'Cargo.toml'), 'utf8')
  const packageSection = manifest.match(/^\[package\]\s*\r?\n((?:(?!^\[)[\s\S])*)/m)
  const version = packageSection?.[1].match(/^version\s*=\s*"([^"]+)"\s*$/m)?.[1]

  if (!version) throw new Error('Could not read [package].version from Cargo.toml')
  return version
}

function releaseModule(version) {
  const tag = `v${version}`
  const releasesUrl = 'https://github.com/dccif/KeySteer/releases'
  const downloadUrl = `${releasesUrl}/download/${tag}`

  return `// Generated by scripts/sync-doc-assets.mjs. Do not edit.\n\nexport const RELEASE_VERSION = ${JSON.stringify(version)}\nexport const RELEASE_TAG = ${JSON.stringify(tag)}\nexport const RELEASES_URL = ${JSON.stringify(releasesUrl)}\nexport const RELEASE_URL = ${JSON.stringify(`${releasesUrl}/tag/${tag}`)}\n\nconst RELEASE_DOWNLOAD_URL = ${JSON.stringify(downloadUrl)}\n\nexport function releaseAssetUrl(target: string) {\n  return \`${'${RELEASE_DOWNLOAD_URL}'}/KeySteer-${'${RELEASE_TAG}'}-${'${target}'}.zip\`\n}\n`
}

await mkdir(output, { recursive: true })
await mkdir(generatedSource, { recursive: true })
const version = await packageVersion()
await Promise.all([
  copyFile(resolve(root, 'keysteer.default.toml'), resolve(output, 'keysteer.default.toml')),
  copyFile(resolve(root, 'assets/icons/keysteer-icon.png'), resolve(output, 'keysteer-icon.png')),
  writeFile(resolve(generatedSource, 'release.ts'), releaseModule(version)),
])
