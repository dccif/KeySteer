// Legacy simulator events are strings. Match complete known message templates,
// keeping interpolated filenames, commands and notes opaque.
const templates = Object.entries(englishMessages).filter(([key]) => /\{\d+\}/.test(key)).map(([key, value]) => ({
  pattern: new RegExp('^' + key.split(/\{\d+\}/).map(part => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('([\\s\\S]*?)') + '$'), value,
}))

export function translate(text: string, locale: StudioLocale, values: unknown[] = []): string {
  const trimmed = text.trim()
  const translated = locale === 'en' ? englishMessages[trimmed] : undefined
  let result = translated === undefined ? text : text.replace(trimmed, () => translated)
  if (locale === 'en' && translated === undefined && !values.length) {
    for (const template of templates) {
      const match = trimmed.match(template.pattern)
      if (match) { result = text.replace(trimmed, () => template.value.replace(/\{(\d+)\}/g, (_, i) => match[Number(i) + 1])); break }
    }
  }
  return result.replace(/\{(\d+)\}/g, (match, index) => Number(index) < values.length ? String(values[Number(index)]) : match)
}
